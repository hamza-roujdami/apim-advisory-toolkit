"""Report: Excel tracker (Tracker, Credentials, Findings, Recent changes, APIs & backends) and a Markdown summary."""
from __future__ import annotations

from datetime import date
from pathlib import Path

from openpyxl import Workbook
from openpyxl.formatting.rule import CellIsRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.worksheet.datavalidation import DataValidation

FONT = "Arial"
BLUE = "0078D4"
NAVY = "243A5E"
YELLOW = PatternFill("solid", fgColor="FFF2CC")
SEV_FILL = {"Critical": "F8CBAD", "High": "FFC7CE", "Medium": "FFEB9C", "Low": "DDEBF7", "Info": "F2F2F2"}
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def _header(ws, row: int, headers: list[str], widths: list[int]):
    for i, (h, w) in enumerate(zip(headers, widths), 1):
        c = ws.cell(row, i, h)
        c.font = Font(name=FONT, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=BLUE)
        c.border = BORDER
        c.alignment = Alignment(wrap_text=True, vertical="center")
        ws.column_dimensions[c.column_letter].width = w
    ws.row_dimensions[row].height = 30


def _cell(ws, r, c, v, wrap=False, fill=None):
    cell = ws.cell(r, c, v)
    cell.font = Font(name=FONT, size=10)
    cell.border = BORDER
    cell.alignment = Alignment(vertical="top", wrap_text=wrap)
    if fill:
        cell.fill = fill
    return cell


def _table(wb, title: str, headers: list[str], widths: list[int], rows: list[list], wrap_from: int = 1,
           yellow: tuple[int, ...] = (), sev_col: int | None = None, freeze: str = "B2"):
    ws = wb.create_sheet(title)
    _header(ws, 1, headers, widths)
    for r, vals in enumerate(rows, 2):
        for c, v in enumerate(vals, 1):
            fill = YELLOW if c in yellow else None
            if sev_col == c and v in SEV_FILL:
                fill = PatternFill("solid", fgColor=SEV_FILL[v])
            _cell(ws, r, c, v, wrap=c >= wrap_from, fill=fill)
    ws.freeze_panes = freeze
    ws.auto_filter.ref = f"A1:{ws.cell(1, len(headers)).column_letter}{max(len(rows) + 1, 2)}"
    return ws


def _affected(a: dict) -> bool:
    return a.get("affectedTier", a.get("classic", False))


def build_excel(assess_rows: list[dict], inv: list[dict], out: Path, customer: str,
                tracking_id: str, cve: str) -> Path:
    inv_by_id = {d["instance"]["id"]: d for d in inv}
    wb = Workbook()
    ws = wb.active
    ws.title = "Tracker"
    title = f"{cve}: Azure API Management advisory - {customer}" if cve else f"APIM security advisory - {customer}"
    ws["A1"] = title
    ws["A1"].font = Font(name=FONT, bold=True, size=14, color=NAVY)
    ws["A2"] = "Service Health tracking ID:"
    ws["C2"] = tracking_id or "-"
    ws["A3"] = "Generated:"
    ws["C3"] = date.today().isoformat()
    for c in ("A2", "A3"):
        ws[c].font = Font(name=FONT, bold=True, size=10)
    ws["A4"] = ("Yellow columns = fill in during remediation. Other tabs are generated by the toolkit - "
                "re-run `apimtk run` to refresh. Affected tiers: Developer, Basic, Standard, Premium.")
    ws["A4"].font = Font(name=FONT, italic=True, size=9, color="595959")
    hdr = ["Priority", "APIM instance", "Subscription", "Tier", "Affected tier?", "In advisory?", "Runtime (NSM check)",
           "Credentials to rotate", "Critical", "High", "Actions performed (date - action)", "Owner", "Status", "Next step"]
    _header(ws, 6, hdr, [8, 30, 26, 11, 9, 11, 14, 11, 8, 8, 50, 14, 13, 45])
    yellow = (11, 12, 13)
    r = 7
    for a in sorted(assess_rows, key=lambda x: (x["priority"], x["name"])):
        d = inv_by_id.get(a["id"], {})
        s = d.get("summary", {})
        nxt = ""
        if d:
            top = [f for f in d["findings"] if f["severity"] in ("Critical", "High")][:2]
            nxt = "; ".join(f"{f['item']}: {f['action']}" for f in top)
        elif not _affected(a):
            nxt = "Tier not affected by the advisory"
        runtime = f"{d.get('runtimeStatus')}\n{d.get('runtimeVersion') or ''}".strip() if d else ""
        vals = [a["priority"], a["name"], f"{a.get('subscriptionName') or ''}\n{a['subscriptionId']}",
                f"{a['sku']} ({a.get('capacity') or 1})", "Yes" if _affected(a) else "No", a["inAdvisory"], runtime,
                d.get("credentialCount", ""), s.get("Critical", ""), s.get("High", ""), "", "",
                "Not started" if _affected(a) else "N/A", nxt]
        for c, v in enumerate(vals, 1):
            _cell(ws, r, c, v, wrap=c in (2, 3, 7, 11, 14), fill=YELLOW if c in yellow else None)
        r += 1
    last = max(r + 20, 30)
    for rr in range(r, last):
        for c in range(1, 15):
            _cell(ws, rr, c, None, fill=YELLOW if c in yellow else None)
    dv = DataValidation(type="list", formula1='"Not started,In progress,Blocked,Done,N/A"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"M7:M{last}")
    for t, col in [("Done", "C6EFCE"), ("Blocked", "FFC7CE"), ("In progress", "FFEB9C")]:
        ws.conditional_formatting.add(f"M7:M{last}", CellIsRule(operator="equal", formula=[f'"{t}"'],
                                                                 fill=PatternFill("solid", fgColor=col)))
    ws.freeze_panes = "C7"
    ws.auto_filter.ref = f"A6:N{last}"
    ws.page_setup.orientation = "landscape"
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0

    _table(wb, "Credentials",
           ["Instance", "Severity", "Type", "Credential", "Used by / where", "Stored", "Action",
            "Rotated at source (date)", "Old one revoked (date)"],
           [28, 10, 22, 40, 34, 20, 55, 16, 16],
           [[d["instance"]["name"], x["severity"], x["kind"], x["name"], x["where"], x["stored"], x["action"], None, None]
            for d in inv for x in d.get("credentials", [])],
           wrap_from=4, yellow=(8, 9), sev_col=2)

    _table(wb, "Findings", ["Instance", "Severity", "Area", "Item", "Detail", "Action"], [30, 10, 18, 32, 45, 60],
           [[d["instance"]["name"], f["severity"], f["area"], f["item"], f["detail"], f["action"]]
            for d in inv for f in d["findings"]], wrap_from=4, sev_col=2)

    _table(wb, "Recent changes", ["Instance", "Caller", "Operation", "Count", "First", "Last", "Expected? (y/n)"],
           [28, 36, 60, 8, 22, 22, 14],
           [[d["instance"]["name"], g["caller"], g["operation"], g["count"], g["first"], g["last"], None]
            for d in inv for g in d.get("recentChanges", [])], wrap_from=2, yellow=(7,))

    rows = [[d["instance"]["name"], "API", a["name"], a.get("path") or "", a.get("serviceUrl") or "",
             "" if a.get("subscriptionRequired") is None else ("Yes" if a["subscriptionRequired"] else "No"), None]
            for d in inv for a in d.get("apis", [])]
    rows += [[d["instance"]["name"], "Backend", b["name"], "", b["url"], "", None]
             for d in inv for b in d.get("backends", [])]
    _table(wb, "APIs & backends", ["Instance", "Kind", "Name", "Path", "Backend URL", "Subscription required",
                                   "Data / system behind it"], [28, 9, 28, 20, 50, 12, 40], rows, wrap_from=3,
           yellow=(7,))

    out.parent.mkdir(parents=True, exist_ok=True)
    wb.save(out)
    return out


def build_markdown(assess_rows: list[dict], inv: list[dict], customer: str, tracking_id: str, cve: str) -> str:
    lines = [f"# APIM advisory report - {customer}", "",
             f"- Tracking ID: **{tracking_id or '-'}**" + (f" | Reference: **{cve}**" if cve else ""),
             f"- Generated: {date.today().isoformat()}",
             f"- Instances found: {len(assess_rows)} | On an affected tier: {sum(_affected(a) for a in assess_rows)} | "
             f"In advisory: {sum(a['inAdvisory'] == 'Yes' for a in assess_rows)}", "",
             "| Priority | Instance | Tier | In advisory | Runtime | Credentials to rotate | Critical | High |",
             "|---|---|---|---|---|---|---|---|"]
    by_id = {d["instance"]["id"]: d for d in inv}
    for a in sorted(assess_rows, key=lambda x: (x["priority"], x["name"])):
        d = by_id.get(a["id"], {})
        s = d.get("summary", {})
        lines.append(f"| {a['priority']} | {a['name']} | {a['sku']} | {a['inAdvisory']} | {d.get('runtimeStatus', '-')} | "
                     f"{d.get('credentialCount', '-')} | {s.get('Critical', '-')} | {s.get('High', '-')} |")
    for d in inv:
        crit = [f for f in d["findings"] if f["severity"] in ("Critical", "High")]
        if crit:
            lines += ["", f"## {d['instance']['name']}", ""]
            lines += [f"- **{f['severity']}** - {f['item']}: {f['detail']} -> _{f['action']}_" for f in crit]
    return "\n".join(lines) + "\n"
